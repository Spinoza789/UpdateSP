vi.mock("@workspace/db", async () => {
  const schema = await import("@workspace/db/schema");
  const dialect = new PgDialect();
  function matches(table: any, predicate: any, row: Row) {
    if (!predicate) return true;
    const { sql, params } = dialect.sqlToQuery(predicate);
    const columns = Object.entries(getTableColumns(table));
    const expression = sql
      .replace(/"[^"]+"\."([^"]+)"/g, (_, name) =>
        `row[${JSON.stringify(columns.find(([, column]) => (column as any).name === name)?.[0] ?? name)}]`)
      .replace(/\$(\d+)/g, (_, index) => `params[${Number(index) - 1}]`)
      .replace(/(row\["[^"]+"\]) in \(([^)]+)\)/gi, "[$2].includes($1)")
      .replace(/\bIS NULL\b/gi, "== null")
      .replace(/\band\b/gi, "&&").replace(/\bor\b/gi, "||")
      .replace(/ <> /g, " !== ").replace(/ = /g, " === ");
    // Evaluate only SQL generated by these route fixtures; no external input is code.
    return new Function("row", "params", "lower", `return (${expression})`)(row, params, (v: unknown) => String(v ?? "").toLowerCase());
  }
  const rows = (table: any) => state.tables[getTableName(table)] ?? [];
  const db = {
    select(fields?: Row) {
      let table: any, predicate: any;
      const query: any = {
        from(t: any) { table = t; return query; },
        where(p: any) { predicate = p; return query; },
        orderBy() { return query; },
        limit() { return query; },
        then(resolve: any, reject: any) {
          const result = rows(table).filter(row => matches(table, predicate, row));
          return Promise.resolve(fields ? result.map(row => Object.fromEntries(Object.entries(fields).map(([key, column]) => {
            const entry = Object.entries(getTableColumns(table)).find(([, value]) => value === column);
            return [key, row[entry?.[0] ?? key]];
          }))) : result).then(resolve, reject);
        },
      };
      return query;
    },
    query: { groupBuysTable: { findFirst: async ({ where }: any) =>
      rows(schema.groupBuysTable).find(row => matches(schema.groupBuysTable, where, row)) } },
    insert(table: any) {
      return { values(value: Row) {
        const inserted = { ...value, createdAt: new Date().toISOString(), lastChecked: null };
        const result: any = {
          returning: async () => { rows(table).push(inserted); return [inserted]; },
          then(resolve: any) { rows(table).push(inserted); return Promise.resolve([]).then(resolve); },
        };
        return result;
      } };
    },
    update(table: any) {
      return { set(value: Row) { return { where(predicate: any) {
        const apply = () => rows(table).filter(row => matches(table, predicate, row)).map(row => Object.assign(row, value));
        return { returning: async () => apply(), then: (resolve: any) => Promise.resolve(apply()).then(resolve) };
      } }; } };
    },
    delete(table: any) { return { where: async (predicate: any) => {
      state.tables[getTableName(table)] = rows(table).filter(row => !matches(table, predicate, row));
    } }; },
  };
  return { ...schema, db, pool: {} };
});
