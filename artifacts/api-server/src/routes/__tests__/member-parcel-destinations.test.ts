import organiserRouter from "../organiser";
import parcelRouter from "../gb-parcels";
import accountRouter from "../account";
let server: Server, base: string;
beforeAll(async () => {
  const app = express();
  app.use(express.json(), organiserRouter, parcelRouter, accountRouter);
  await new Promise<void>(resolve => { server = app.listen(0, "127.0.0.1", () => resolve()); });
  base = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
});
afterAll(async () => { if (server) await new Promise<void>(resolve => server.close(() => resolve())); });
beforeEach(() => {
  state.tables = {
    group_buys: [{ id: "G", organiserId: "owner" }, { id: "OTHER", organiserId: "other" }],
    gb_reshippers: [{ gbId: "G", reshipperUsername: "alpha" }, { gbId: "G", reshipperUsername: "beta" }, { gbId: "OTHER", reshipperUsername: "foreign" }],
    account_group_buys: [{ id: "m", groupBuyId: "G", accountId: "@Member" }, { id: "n", groupBuyId: "G", accountId: "second" }],
    orders: [
      { id: "o", groupBuyId: "G", telegramUsername: "@Member", paymentStatus: "confirmed", reshipperUsername: "@ALPHA", routingType: "direct", directShippingRequested: true, status: "Processing", deletedAt: null },
      { id: "p", groupBuyId: "G", telegramUsername: "second", paymentStatus: "confirmed", reshipperUsername: "beta", status: "Processing", deletedAt: null },
    ],
    order_line_items: [{ orderId: "o", productName: "Product", quantity: "2" }, { orderId: "p", productName: "Product", quantity: "5" }],
    gb_parcels: [],
  };
});
async function request(path: string, body?: Row, role: "organiser" | "admin" | "member" = "organiser", method = body ? "POST" : "GET", name?: string) {
  const response = await fetch(`${base}${path}`, {
    method, headers: { "content-type": "application/json", [`x-test-${role}`]: name ?? (role === "organiser" ? "owner" : role === "admin" ? "yes" : "member") },
    body: body ? JSON.stringify(body) : undefined,
  });
  return { status: response.status, body: await response.json() as any };
}
const payload = { label: "Package 1 - AJ", trackingNumber: "SECRET123", carrier: "Auto",
  items: [{ name: "Product", qty: 100 }, { name: "Private", qty: 20 }] };
const endpoints = ["/group-buys/G/parcels", "/account/group-buys/G/parcels"];

describe("organiser/Admin destination writes through both member parcel endpoints", () => {
  it("repairs a legacy parcel in place, preserves history, reloads assignment, and isolates same-product members", async () => {
    const created = await request("/organiser/group-buys/G/parcels", payload);
    expect(created.status).toBe(201);
    for (const endpoint of endpoints) expect((await request(endpoint, undefined, "member")).body).toEqual([]);
    const id = created.body.id;
    const events = [{ date: "2026-10-01T00:00:00.000Z", status: "In transit", location: "China" }];
    state.tables.gb_parcels[0].cachedEvents = events;
    const saved = await request(`/organiser/group-buys/G/parcels/${id}`, { reshipperUsername: " @Alpha " }, "organiser", "PATCH");
    expect(saved.body).toMatchObject({ ...payload, reshipperUsername: "alpha", cachedEvents: events });
    expect((await request("/organiser/group-buys/G/parcels")).body[0].reshipperUsername).toBe("alpha");
    await request(`/organiser/group-buys/G/parcels/${id}`, { notes: "Unrelated edit" }, "organiser", "PATCH");
    for (const endpoint of endpoints) {
      const read = await request(endpoint, undefined, "member");
      expect(read.status).toBe(200);
      expect(read.body).toHaveLength(1);
      expect(read.body[0]).toMatchObject({ items: [{ name: "Product", qty: 2 }], events, trackingUrl: null });
      expect(JSON.stringify(read.body)).not.toContain("SECRET123");
      expect((await request(endpoint, undefined, "member", "GET", "second")).body).toEqual([]);
    }
  });
  it("persists Admin create/edit destinations and preserves omitted assignments", async () => {
    const created = await request("/admin/group-buys/G/parcels", { ...payload, reshipperUsername: "BETA" }, "admin");
    expect(created.status).toBe(201);
    expect(created.body.reshipperUsername).toBe("beta");
    const updated = await request(`/admin/group-buys/G/parcels/${created.body.id}`, { notes: "Keep destination" }, "admin", "PATCH");
    expect(updated.body.reshipperUsername).toBe("beta");
    const repaired = await request(`/admin/group-buys/G/parcels/${created.body.id}`, { reshipperUsername: "alpha" }, "admin", "PATCH");
    expect(repaired.body.items).toEqual(payload.items);
    for (const endpoint of endpoints) expect((await request(endpoint, undefined, "member")).body).toHaveLength(1);
  });
  it("rejects foreign destinations, foreign-group parcel updates, and non-owner organisers", async () => {
    for (const role of ["admin", "organiser"] as const) {
      expect((await request(`/${role}/group-buys/G/parcels`, { ...payload, reshipperUsername: "foreign" }, role)).status).toBe(400);
    }
    const created = await request("/organiser/group-buys/G/parcels", { ...payload, reshipperUsername: "alpha" });
    for (const role of ["admin", "organiser"] as const) {
      expect((await request(`/${role}/group-buys/OTHER/parcels/${created.body.id}`, { notes: "bad" }, role, "PATCH", role === "organiser" ? "other" : "yes")).status).toBe(404);
    }
    expect((await request("/organiser/group-buys/G/parcels", payload, "organiser", "POST", "other")).status).toBe(404);
    expect(state.tables.gb_parcels[0].notes).toBeNull();
  });
  it("keeps membership and payment gates on both projections", async () => {
    for (const endpoint of endpoints) expect((await request(endpoint, undefined, "member", "GET", "outsider")).status).toBe(403);
    state.tables.orders[0].paymentStatus = "unpaid";
    for (const endpoint of endpoints) expect((await request(endpoint, undefined, "member")).status).toBe(403);
  });
  it("keeps direct and reshipper items separate in mixed orders on both endpoints", async () => {
    await request("/organiser/group-buys/G/parcels", { ...payload, reshipperUsername: "alpha" });
    await request("/organiser/group-buys/G/parcels", { ...payload, label: "Package - Ghost", reshipperUsername: "beta" });
    state.tables.orders.push({
      id: "direct", groupBuyId: "G", telegramUsername: "MEMBER", status: "Shipped",
      paymentStatus: "confirmed", deletedAt: null, directShippingRequested: true,
      routingType: "direct", reshipperUsername: null, trackingNumber: "PERSONAL123",
    });
    state.tables.order_line_items.push({ orderId: "direct", productName: "Direct product", quantity: "3" });
    for (const endpoint of endpoints) {
      const read = (await request(endpoint, undefined, "member")).body;
      expect(read).toHaveLength(2);
      expect(read.find((row: Row) => row.id.startsWith("order-"))).toMatchObject({
        maskedTrackingNumber: "PERSONAL123", items: [{ name: "Direct product", qty: 3 }],
      });
      const other = (await request(endpoint, undefined, "member", "GET", "@SECOND")).body;
      expect(other).toHaveLength(1);
      expect(other[0]).toMatchObject({ label: "Package - Ghost", items: [{ name: "Product", qty: 5 }] });
    }
  });
  it("does not grant parcel access through deleted or cancelled paid orders", async () => {
    state.tables.orders[0].deletedAt = new Date();
    for (const endpoint of endpoints) expect((await request(endpoint, undefined, "member")).status).toBe(403);
    state.tables.orders[0].deletedAt = null;
    state.tables.orders[0].status = "Cancelled";
    for (const endpoint of endpoints) expect((await request(endpoint, undefined, "member")).status).toBe(403);
  });
  it("resolves a legacy order leg only through one enabled same-group assignment, never the parcel country", async () => {
    Object.assign(state.tables.orders[0], { reshipperUsername: null, countryLegId: "UK", routingType: "reshipper", directShippingRequested: false });
    state.tables.gb_country_legs = [{ id: "UK", gbId: "G", countryCode: "GB" }];
    Object.assign(state.tables.gb_reshippers[0], { country: "United Kingdom", countries: ["UK"], enabled: true });
    Object.assign(state.tables.gb_reshippers[1], { country: "Germany", enabled: true });
    state.tables.gb_reshippers.push({ gbId: "OTHER", country: "GB", reshipperUsername: "foreign", enabled: true });
    const created = await request("/organiser/group-buys/G/parcels", payload);
    for (const endpoint of endpoints) expect((await request(endpoint, undefined, "member")).body).toEqual([]);
    await request(`/organiser/group-buys/G/parcels/${created.body.id}`, { reshipperUsername: "alpha" }, "organiser", "PATCH");
    for (const endpoint of endpoints) {
      const read = (await request(endpoint, undefined, "member")).body;
      expect(read).toHaveLength(1);
      expect(read[0].items).toEqual([{ name: "Product", qty: 2 }]);
      expect((await request(endpoint, undefined, "member", "GET", "second")).body).toEqual([]);
    }
    // Two authorised assignments for the order's leg are ambiguous.
    state.tables.gb_reshippers[1].country = "GB";
    for (const endpoint of endpoints) expect((await request(endpoint, undefined, "member")).body).toEqual([]);
    Object.assign(state.tables.orders[0], { reshipperUsername: "@ALPHA", routingType: "direct" });
    for (const endpoint of endpoints) expect((await request(endpoint, undefined, "member")).body).toHaveLength(1);
    Object.assign(state.tables.orders[0], { reshipperUsername: null, routingType: "reshipper" });
    state.tables.gb_reshippers[1].enabled = false;
    for (const endpoint of endpoints) expect((await request(endpoint, undefined, "member")).body).toHaveLength(1);
    // A foreign leg ID or an explicit direct route never resolves through country overlap.
    state.tables.gb_country_legs[0].gbId = "OTHER";
    for (const endpoint of endpoints) expect((await request(endpoint, undefined, "member")).body).toEqual([]);
    state.tables.gb_country_legs[0].gbId = "G";
    state.tables.orders[0].directShippingRequested = true;
    for (const endpoint of endpoints) expect((await request(endpoint, undefined, "member")).body).toEqual([]);
    Object.assign(state.tables.orders[0], { directShippingRequested: false, routingType: "direct" });
    for (const endpoint of endpoints) expect((await request(endpoint, undefined, "member")).body).toEqual([]);
    Object.assign(state.tables.orders[0], { routingType: "reshipper" });
    state.tables.gb_reshippers[0].enabled = false;
    for (const endpoint of endpoints) expect((await request(endpoint, undefined, "member")).body).toEqual([]);
  });
});
