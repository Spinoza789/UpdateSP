/* ---------------------------------------------------------------------------
 * Vendor notification feed with priorities: bell + panel in the top bar, and a
 * critical-items banner for Home. Priorities: critical > high > normal > low.
 * ------------------------------------------------------------------------- */
export type Priority = "critical" | "high" | "normal" | "low";
export interface VendorNotification {
  id: string; priority: Priority; kind: string; title: string; body: string | null; link: string | null; submissionId: string | null; read: boolean; readAt: string | null; createdAt: string;
}
/** Only translate templates generated by the server; administrator notes stay verbatim. */
export function notificationText(notification: Pick<VendorNotification, "kind" | "title" | "body">, field: "title" | "body", language = getVendorLanguage()): string | null {
  const text = notification[field];
  if (language !== "zh" || text == null) return text;
  const titlePatterns: Record<string, [RegExp, (...values: string[]) => string][]> = {
    new_order: [[/^New shipment #(.+)$/, reference => `新发货任务 #${reference}`]],
    hold: [[/^Order #(.+) put on hold$/, reference => `订单 #${reference} 已暂停`]],
    overdue: [[/^#(.+) has waited (\d+)h without tracking$/, (reference, hours) => `#${reference} 已等待 ${hours} 小时，尚无物流信息`]],
    overdue_critical: [[/^#(.+) is (\d+)h\+ overdue$/, (reference, hours) => `#${reference} 已逾期 ${hours} 小时以上`]],
    issue_resolved: [[/^Problem report answered(?: · #(.+))?$/, reference => `问题报告已回复${reference ? ` · #${reference}` : ""}`]],
    settings: [
      [/^Peps Anonymous paused your new orders until (\d{4}-\d{2}-\d{2})$/, date => `Peps Anonymous 已暂停向您分配新订单，直至 ${date}`],
      [/^Peps Anonymous reopened your order routing$/, () => "Peps Anonymous 已恢复向您分配订单"],
    ],
    security: [
      [/^Authenticator app turned on$/, () => "身份验证器应用已启用"],
      [/^Authenticator app turned off$/, () => "身份验证器应用已停用"],
      [/^Passkey added: (.+)$/, name => `已添加通行密钥：${name}`],
      [/^Passkey removed$/, () => "通行密钥已移除"],
    ],
    security_reset: [[/^Two-step verification reset for (.+)$/, username => `${username} 的两步验证已重置`]],
  };
  if (field === "title") {
    for (const [pattern, format] of titlePatterns[notification.kind] ?? []) {
      const match = text.match(pattern);
      if (match) return format(...match.slice(1));
    }
    return text;
  }
  const bodies: Record<string, [string, string]> = {
    new_order: ["Assigned to you. Open it to start packing.", "已分配给您。打开订单即可开始打包。"],
    hold: ["Peps Anonymous changed this order. Do not pack it until it is resubmitted.", "Peps Anonymous 已更改此订单。重新提交前请勿打包。"],
    overdue: ["Add tracking or report a problem.", "请添加物流信息或报告问题。"],
    overdue_critical: ["The customer is waiting. Add tracking now or report a problem.", "客户正在等待，请立即添加物流信息或报告问题。"],
    issue_resolved: ["Marked as resolved by Peps Anonymous.", "Peps Anonymous 已标记为已解决。"],
    security_reset: ["Peps Anonymous removed the authenticator app and passkeys from this account. Set them up again in Settings → Security. If you did not ask for this, contact Peps Anonymous now.", "Peps Anonymous 已移除此账户的身份验证器应用和通行密钥。请在设置 → 安全中重新设置。若非您本人要求，请立即联系 Peps Anonymous。"],
  };
  const known = bodies[notification.kind];
  if (known && text === known[0]) return known[1];
  if (notification.kind === "security" || notification.kind === "security_reset") {
    const match = text.match(/^Account (.+)\. If this was not you, contact Peps Anonymous immediately\.$/);
    if (match) return `账户 ${match[1]}。若非您本人操作，请立即联系 Peps Anonymous。`;
  }
  return text;
}

export type UnreadCounts = Record<Priority | "total", number>;
export const PRIORITY_META: Record<Priority, { label: string; tone: Tone; dot: string }> = {
  critical: { label: "Critical", tone: "critical", dot: "#E51C00" },
  high: { label: "High", tone: "attention", dot: "#B98900" },
  normal: { label: "Normal", tone: "info", dot: "#2D6BCC" },
  low: { label: "Low", tone: "neutral", dot: "#8A8A8A" },
};
const ORDER: Priority[] = ["critical", "high", "normal", "low"];
export const highestUnread = (u: UnreadCounts | null): Priority | null => u ? ORDER.find(p => u[p] > 0) ?? null : null;

/** Links stored on notifications are portal-relative: "?order=<id>", "?thread=<id>", "settings". */
export type NotificationTarget = { kind: "order"; id: string } | { kind: "thread"; id: string } | { kind: "settings" } | null;
export function parseLink(link: string | null): NotificationTarget {
  if (!link) return null;
  if (link === "settings") return { kind: "settings" };
  const params = new URLSearchParams(link.startsWith("?") ? link : `?${link}`);
  const order = params.get("order"), thread = params.get("thread");
  if (order) return { kind: "order", id: order };
  if (thread) return { kind: "thread", id: thread };
  return null;
}
const when = (v: string) => { const d = new Date(v); if (isNaN(d.getTime())) return ""; const diff = Date.now() - d.getTime(); const m = Math.floor(diff / 60_000); if (m < 1) return vt("just now"); if (m < 60) return (getVendorLanguage() === "zh" ? `${m} 分钟前` : `${m}m ago`); const h = Math.floor(m / 60); if (h < 24) return (getVendorLanguage() === "zh" ? `${h} 小时前` : `${h}h ago`); return d.toLocaleDateString(getVendorLanguage() === "zh" ? "zh-CN" : "en-GB", { month: "short", day: "numeric" }); };

export function useVendorNotifications(enabled: boolean) {
  const [items, setItems] = useState<VendorNotification[]>([]);
  const [unread, setUnread] = useState<UnreadCounts | null>(null);
  const refresh = useCallback(async () => {
    if (!enabled) return;
    try {
      const r = await vendorFetch("/api/vendor/notifications?limit=60");
      if (!r.ok) return;
      const b = await r.json();
      setItems(Array.isArray(b?.notifications) ? b.notifications : []); setUnread(b?.unread ?? null);
    } catch { /* keep last state */ }
  }, [enabled]);
  useEffect(() => { void refresh(); if (!enabled) return; const t = setInterval(refresh, 30_000); return () => clearInterval(t); }, [enabled, refresh]);
  const markRead = useCallback(async (ids: string[]) => {
    if (!ids.length) return;
    setItems(list => list.map(n => ids.includes(n.id) ? { ...n, read: true } : n));
    const r = await vendorFetch("/api/vendor/notifications/read", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ ids }) }).catch(() => null);
    if (r?.ok) setUnread((await r.json()).unread ?? null);
  }, []);
  const markAllRead = useCallback(async () => {
    setItems(list => list.map(n => ({ ...n, read: true })));
    const r = await vendorFetch("/api/vendor/notifications/read", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ all: true }) }).catch(() => null);
    if (r?.ok) setUnread((await r.json()).unread ?? null);
  }, []);
  return { items, unread, refresh, markRead, markAllRead };
}

export function NotificationBell({ items, unread, onOpenTarget, markRead, markAllRead }: {
  items: VendorNotification[]; unread: UnreadCounts | null; onOpenTarget: (target: NotificationTarget) => void; markRead: (ids: string[]) => Promise<void>; markAllRead: () => Promise<void>;
}) {
  useVendorLanguage();
  const [open, setOpen] = useState(false);
  const [filter, setFilter] = useState<Priority | "all">("all");
  const ref = useRef<HTMLDivElement>(null);
  useEffect(() => {
    if (!open) return;
    const onDoc = (e: MouseEvent) => { if (ref.current && !ref.current.contains(e.target as Node)) setOpen(false); };
    const onKey = (e: KeyboardEvent) => { if (e.key === "Escape") setOpen(false); };
    document.addEventListener("mousedown", onDoc); document.addEventListener("keydown", onKey);
    return () => { document.removeEventListener("mousedown", onDoc); document.removeEventListener("keydown", onKey); };
  }, [open]);
  const top = highestUnread(unread);
  const total = unread?.total ?? 0;
  const visible = useMemo(() => items.filter(n => filter === "all" || n.priority === filter), [items, filter]);
  const grouped = useMemo(() => ORDER.map(p => ({ priority: p, list: visible.filter(n => n.priority === p && !n.read) })).filter(g => g.list.length), [visible]);
  const earlier = useMemo(() => visible.filter(n => n.read).slice(0, 20), [visible]);

  const openItem = (n: VendorNotification) => { if (!n.read) void markRead([n.id]); const target = parseLink(n.link); if (target) { setOpen(false); onOpenTarget(target); } };
  const Item = ({ n }: { n: VendorNotification }) => (
    <li>
      <button type="button" onClick={() => openItem(n)} className="w-full text-left px-4 py-2.5 flex gap-3 hover:bg-[var(--t-surface2)]" data-testid={`notification-${n.id}`}>
        <span className="mt-1.5 w-2 h-2 rounded-full shrink-0" style={{ background: n.read ? "transparent" : PRIORITY_META[n.priority].dot, boxShadow: n.read ? `inset 0 0 0 1px ${PRIORITY_META[n.priority].dot}` : undefined }} aria-hidden />
        <span className="min-w-0 flex-1">
          <span className="flex items-center gap-2"><span className={`text-[13px] truncate ${n.read ? "font-medium" : "font-semibold"}`} style={{ color: "var(--t-text)" }}>{notificationText(n, "title")}</span><span className="ml-auto text-[11px] shrink-0" style={subtle}>{when(n.createdAt)}</span></span>
          {n.body && <span className="block text-xs mt-0.5 line-clamp-2" style={muted}>{notificationText(n, "body")}</span>}
        </span>
        {n.link && <ChevronRight className="w-4 h-4 shrink-0 self-center" style={subtle} />}
      </button>
    </li>
  );

  return (
    <div className="relative" ref={ref}>
      <button type="button" onClick={() => setOpen(o => !o)} aria-label={total ? (getVendorLanguage() === "zh" ? `${total} 条未读通知` : `${total} unread notifications`) : vt("Notifications")} aria-expanded={open}
        className="relative w-9 h-9 rounded-lg grid place-items-center hover:bg-white/10 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-white/60" data-testid="button-notifications">
        <Bell className="w-[18px] h-[18px]" />
        {total > 0 && <span className="absolute -top-0.5 -right-0.5 min-w-[18px] h-[18px] px-1 rounded-full text-[10px] font-bold grid place-items-center text-white" style={{ background: PRIORITY_META[top ?? "normal"].dot, boxShadow: "0 0 0 2px #1A1A1A" }} data-testid="badge-notifications">{total > 99 ? "99+" : total}</span>}
      </button>
      {open && (
        <div className="absolute right-0 mt-2 w-[380px] max-w-[calc(100vw-24px)] rounded-xl overflow-hidden z-50" style={{ background: "var(--t-surface)", border: "1px solid var(--t-border)", boxShadow: "0 12px 32px rgba(0,0,0,0.18)", color: "var(--t-text)" }} role="dialog" aria-label={vt("Notifications")} data-testid="panel-notifications">
          <div className="flex items-center gap-2 px-4 pt-3 pb-2">
            <h2 className="text-[13px] font-semibold">{vt("Notifications")}</h2>
            {total > 0 && <Btn variant="plain" className="ml-auto !h-7" onClick={() => void markAllRead()} data-testid="button-mark-all-read"><CheckCheck className="w-4 h-4" />{vt("Mark all read")}</Btn>}
            <button type="button" onClick={() => setOpen(false)} aria-label={vt("Close")} className={`${total ? "" : "ml-auto"} p-1 rounded hover:bg-[var(--t-surface2)]`}><X className="w-4 h-4" /></button>
          </div>
          <div className="flex items-center gap-1 px-3 pb-2 overflow-x-auto" role="tablist">
            {(["all", ...ORDER] as const).map(p => {
              const count = p === "all" ? total : unread?.[p] ?? 0; const on = filter === p;
              return <button key={p} role="tab" aria-selected={on} onClick={() => setFilter(p)} className="h-7 px-2.5 rounded-lg text-xs whitespace-nowrap flex items-center gap-1.5" style={{ background: on ? "var(--t-surface2)" : undefined, color: on ? "var(--t-text)" : "var(--t-muted)", fontWeight: on ? 600 : 500 }}>
                {p !== "all" && <span className="w-2 h-2 rounded-full" style={{ background: PRIORITY_META[p].dot }} />}{p === "all" ? vt("All") : vt(PRIORITY_META[p].label)}{count > 0 && <span className="tabular-nums" style={subtle}>{count}</span>}
              </button>;
            })}
          </div>
          <div className="max-h-[70vh] overflow-y-auto" style={{ borderTop: "1px solid var(--t-border)" }}>
            {grouped.length === 0 && earlier.length === 0 && <p className="px-4 py-8 text-[13px] text-center" style={muted}>{vt("You're all caught up.")}</p>}
            {grouped.map(g => (
              <section key={g.priority}>
                <h3 className="px-4 pt-3 pb-1 text-[11px] font-semibold uppercase tracking-wider flex items-center gap-1.5" style={{ color: PRIORITY_META[g.priority].dot }}><span className="w-2 h-2 rounded-full" style={{ background: PRIORITY_META[g.priority].dot }} />{vt(PRIORITY_META[g.priority].label)}</h3>
                <ul>{g.list.map(n => <Item key={n.id} n={n} />)}</ul>
              </section>))}
            {earlier.length > 0 && <section><h3 className="px-4 pt-3 pb-1 text-[11px] font-semibold uppercase tracking-wider" style={subtle}>{vt("Earlier")}</h3><ul>{earlier.map(n => <Item key={n.id} n={n} />)}</ul></section>}
          </div>
        </div>)}
    </div>
  );
}

/** Home banner: unread critical notifications demand attention before anything else. */
export function CriticalBanner({ items, onOpenTarget, markRead }: { items: VendorNotification[]; onOpenTarget: (t: NotificationTarget) => void; markRead: (ids: string[]) => Promise<void> }) {
  useVendorLanguage();
  const critical = items.filter(n => n.priority === "critical" && !n.read);
  if (!critical.length) return null;
  return (
    <div className="mb-4 space-y-2" data-testid="banner-critical">
      {critical.slice(0, 3).map(n => (
        <Banner key={n.id} tone="critical" role="alert" onDismiss={() => void markRead([n.id])}>
          <span className="font-semibold">{notificationText(n, "title")}.</span> {notificationText(n, "body")}{" "}
          {n.link && <button type="button" className="font-semibold underline" onClick={() => { void markRead([n.id]); onOpenTarget(parseLink(n.link)); }}>{vt("Open")}</button>}
        </Banner>))}
      {critical.length > 3 && <p className="text-xs" style={subtle}>{critical.length - 3} {vt("more critical notification")}{getVendorLanguage() === "zh" || critical.length - 3 === 1 ? "" : "s"} {vt("in the bell menu.")}</p>}
    </div>
  );
}
